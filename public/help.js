  // ------------------------------------------------- หาว่าผู้ใช้อยู่หน้าไหน
  function currentKey() {
    // หน้าผู้ดูแล
    if (document.getElementById('appView') || document.getElementById('loginView')) {
      if (visible('#loginView')) return 'login';
      const tab = document.querySelector('.tabs [role="tab"].active');
      const name = tab ? tab.dataset.tab : 'meetings';
      if (name === 'meetings') {
        if (visible('#meetingForm')) return 'meetingForm';
        if (visible('#responseView')) return 'responses';
        return 'meetings';
      }
      return name;
    }
    // หน้าแบบตอบรับ
    if (visible('#done')) return 'done';
    if (visible('#fullView')) return 'full';
    if (visible('#fatal')) return 'fatal';
    if (visible('#welcome')) return 'welcome';
    if (visible('#form')) {
      const step = document.querySelector('#form .step:not([hidden])');
      if (step && HELP[step.dataset.step]) return step.dataset.step;
    }
    return 'loading';
  }

